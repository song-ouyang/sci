"""Render supplementary tables for the error-structure and screening analyses."""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT / "results/error_structure_v3"
OUT = ROOT / "results/industrial_interface_focused_overleaf/supp_structure_tables.tex"


def read(name):
    with open(BASE / name, newline="") as handle:
        return list(csv.DictReader(handle))


def esc(text):
    return text.replace("_", r"\_").replace("%", r"\%")


def pct(x, digits=1):
    return "--" if x in ("", "None", None) else f"{100 * float(x):.{digits}f}"


def table(caption, label, spec, header, rows, small=r"\scriptsize"):
    body = "\n".join(" & ".join(r) + r" \\" for r in rows)
    return (rf"\begin{{table}}[htbp]\centering{small}" "\n" rf"\caption{{{caption}}}\label{{{label}}}" "\n"
            rf"\resizebox{{\linewidth}}{{!}}{{\begin{{tabular}}{{{spec}}}\toprule" "\n" + header + r" \\\midrule" "\n"
            + body + "\n" + r"\bottomrule\end{tabular}}\end{table}" "\n")


def main():
    parts = []
    audit = read("single_call_audit.csv")
    parts.append(table(
        "Single-call versus call-level evidence for the 19 GPT-5.6 Sol contrasts. Single-call: exact McNemar test on the primary call pair, unadjusted. Call-level support: randomization $p\\le0.10$ and a crossed bootstrap interval excluding zero.",
        "tab:sf_audit", "@{}llrrrl@{}",
        "Family & Contrast & Single-call $p$ & Call-level $p$ & Min.\\ $p$ & Verdict",
        [[esc(r["family"].split("/")[-1]), esc(r["contrast"]), f"{float(r['single_call_p']):.2g}",
          f"{float(r['call_level_p']):.3f}", f"{float(r['min_attainable_p']):.3f}", esc(r["verdict"])] for r in audit]))
    groups = [g for g in read("groups.csv") if int(g["total_errors"]) >= 5]
    rows = []
    for g in sorted(groups, key=lambda g: (g["study"], g["service"], g["group"])):
        k = int(g["calls"])
        err = int(g["total_errors"])
        share = int(g["stable_error"]) * k / err
        single = float(g["error_rate"])
        removed = (single - (1 - float(g["majority_accuracy"]))) / single
        rows.append([esc(g["study"]), "Sol" if "sol" in g["service"] else "Astra", esc(g["group"]), g["n_cases"], str(k),
                     pct(g["accuracy"]), f"{share:.2f}", g["unstable"], g["stable_error"], f"{100 * removed:+.0f}"])
    parts.append(table(
        "Error structure of the 28 identical-input groups with at least five errors. $s$: share of errors that recur in every call. U/SE: unstable and stable-error cases. Vote: percentage of errors removed by a majority over all calls of the group (negative: errors added).",
        "tab:sf_groups", "@{}lllrrrrrrr@{}",
        "Study & Service & Group & $n$ & $k$ & Acc.\\ (\\%) & $s$ & U & SE & Vote (\\%)", rows))
    sens = read("canary_threshold_sensitivity.csv")
    studies = list(dict.fromkeys(r["study"] for r in sens))
    rows = []
    for tau in dict.fromkeys(r["tau"] for r in sens):
        cells = [tau]
        for st in studies:
            r = next(x for x in sens if x["tau"] == tau and x["study"] == st)
            cells.append(f"{r['accepted']}/{r['calls']}, {pct(r['accepted_focal_accuracy'])}")
        rows.append(cells)
    parts.append(table(
        "Canary-threshold sensitivity (GPT-5.6 Sol): accepted calls and focal accuracy of accepted calls (\\%). The threshold used throughout is 0.8.",
        "tab:sf_tau", "@{}l" + "r" * len(studies) + "@{}",
        "$\\tau$ & " + " & ".join(esc(s) for s in studies), rows))
    pol = read("decision_policies.csv")
    parts.append(table(
        "Decision policies on all windows of identical Sol calls that contain canaries, including the prospective study.",
        "tab:sf_policies", "@{}llrrrrrrr@{}",
        "Study & Policy & Windows & Decisions & Correct & Errors & Abstained & Err.\\ (\\%) & Calls/window",
        [[esc(r["study"]), r["policy"], r["windows"], r["decisions"], r["accepted_correct"], r["accepted_error"],
          r["abstained"], pct(r["accepted_error_rate"]), f"{float(r['calls_per_window']):.1f}"] for r in pol]))
    OUT.write_text("% Generated by src/analysis/structure_tables_v3.py; do not edit by hand.\n" + "\n".join(parts))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
